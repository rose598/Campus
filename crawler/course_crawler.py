def _make_generic_template(
    course_name: str,
    department: str,
    credits: int,
    overview: str,
    goals: list,
    prereq: str,
    chapters: list,
    assessment: str,
    textbook: str,
    domain_hint: str,
) -> dict:
    """构造标准结构的课程模板（大纲 + 课件）"""
    syllabus = (
        "一、课程概述\n" + overview + "\n\n"
        "二、教学目标\n" + "\n".join(f"{i+1}. {g}" for i, g in enumerate(goals)) + "\n\n"
        "三、先修课程\n" + f"先修课程：{prereq}\n\n"
        "四、教学内容\n" + "\n".join(f"第{['一','二','三','四','五','六','七','八'][i]}章 {c}" for i, c in enumerate(chapters)) + "\n\n"
        "五、考核方式\n" + assessment + "\n\n"
        "六、教材及参考资料\n" + textbook
    )
    slides = (
        "第{week}周 课件\n\n"
        f"课程：{course_name}\n\n"
        "本讲主题：{topic}\n\n"
        "重点要求：{key_point}\n\n"
        f"核心内容（{domain_hint}）：\n"
        "1. 本讲概念与定义梳理\n"
        "2. 典型例题与解题步骤\n"
        "3. 常见错误与注意事项\n\n"
        "课后任务：\n"
        "- 完成教材对应章节习题\n"
        "- 预习下一讲内容"
    )
    return {
        "course_name": course_name,
        "department": department,
        "credits": credits,
        "syllabus_tpl": syllabus,
        "slides_tpl": slides,
    }


